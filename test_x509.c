static void test_create_x509_certificate_from_asn1()
{
	char* file_name="example.der";

	uint8_t *buffer;
	size_t len;
	FILE *file =fopen(file_name,"rb");
	if(file==NULL) {
		perror("fopen");
		return ;
	}

	fseek(file,0,SEEK_END);
	len=ftell(file);
	fseek(file,0,SEEK_SET);
	buffer=malloc(len);
	if(buffer==NULL) {
		perror("malloc");
		fclose(file);
		return ;
	}
	fread(buffer,1,len,file);
	fclose(file);

	tlv_t tlv = parse_tlv(buffer,len);
	tlv_node_t *root =build_tlv(tlv);
	field_t *parent=create_x509_definition();

	field_value_t *mapping=NULL;
	bool is_valid=validate_schema(parent,root,&mapping);
	TEST_ASSERT_TRUE(is_valid);

	decode(mapping,NULL);
	certificate_t *cert=x509_create_from_asn1(mapping);
	TEST_ASSERT_EQUAL_INT(2,cert->tbsCertificate->version);
  bigint_t r=BIGINT(1,0x76,0x3C,0x5C,0x11,0xA6,0xF5,0x10,0xE9,0xBD,0x49,0x03,0x9E,0x64,0xC0,0x0D,0xF7,0xBF,0x20,0x9A,0xC3,0x57,0xFB,0xF0,0x28,0x1E,0x68,0x34,0x42,0x9B,0xDB,0x1E,0x31);
  bigint_t s=BIGINT(1,0x7C,0x39,0x2F,0x03,0x88,0x9D,0x87,0xEA,0x97,0x3F,0xCC,0xA6,0xEB,0x75,0x7F,0xA0,0x2D,0x4E,0x02,0xD7,0x90,0xEC,0x82,0x08,0x7F,0xDA,0xFD,0xB1,0x4A,0x83,0xDD,0x20);
  TEST_ASSERT_BIGINT_EQUAL(&r,cert->signatureValue->signature.ecdsa.r);
  TEST_ASSERT_BIGINT_EQUAL(&s,cert->signatureValue->signature.ecdsa.s);
  uint8_t expected_hash[]={
    0x38,0xE6,0xDF,0xDC,0x8E,0xE5,0x86,0x90, 0xC6,0x68,0xEB,0x3F,0x63,0x69,0x3B,0x18, 0x29,0x75,0xD8,0x4C,0xCC,0xBF,0x02,0x64, 0x4F,0xF9,0x91,0x58,0x82,0x28,0x6C,0x19
  };
  uint8_t hash[32]={0};
  sha256_hash(cert->tbsCertificate->value,cert->tbsCertificate->value_len,hash);
  TEST_ASSERT_EQUAL_UINT8_ARRAY(expected_hash,hash,32);
  char *curve_id_str=oid_to_str(cert->tbsCertificate->subjectPublicKeyInfo->algorithm->parameters.ec_curve_id);
  ecdsa_params_t params;
  if(strcmp(curve_id_str,"1.2.840.10045.3.1.7")==0) {
    params=ecdsa_params[PRIME256V1];
  }
  ecdsa_signature_t sig = {
    .r=&r,
    .s=&s
  };
  ecdsa_point_t issuer_q = {
    &BIGINT(1,
      0x07,0x21,0xC7,0x20,0x7C,0xAD,0x35,0x2C, 0xD3,0x4B,0xE1,0x77,0x24,0x0E,0xE1,0x1C, 0xC0,0xC6,0x77,0x67,0x29,0x71,0x8F,0x62, 0xDC,0xC2,0xD3,0x2A,0x61,0x3A,0x0C,0x94
    ),
    &BIGINT(1,
      0xCA,0x73,0xA2,0x70,0xBD,0x6E,0x74,0xA7, 0x02,0xA8,0x76,0xF7,0x76,0x42,0x3E,0x11, 0x00,0x0C,0xB6,0x8D,0x27,0xA3,0xB1,0x58, 0x30,0xE6,0x37,0xA1,0xEA,0xCC,0xAD,0xDC
    )
  };
  bigint_t *z = create_bigint(hash,32);
  bool valid =
    ecdsa_signature_verify(
      params,
      sig,
      z,
      issuer_q
    );
  TEST_ASSERT_TRUE(valid);
}

int main(void)
{
  UNITY_BEGIN();
  RUN_TEST(test_create_x509_certificate_from_asn1);
  return UNITY_END();
}
